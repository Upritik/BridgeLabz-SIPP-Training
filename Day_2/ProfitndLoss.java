package Day_2;

public class ProfitndLoss {
    public static void main(String[] args){
        int cp=121;
        int sp=191;
        int profit = sp-cp;
        int profitpercentage=profit/cp*100;
        System.out.println("Profit is "+profit);
        System.out.println("Profit percentage is "+profitpercentage+"%");
    }
}
